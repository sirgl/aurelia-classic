#!/usr/bin/env python3
"""Writes assets/lang/en/content-classic.ftl: the English names and texts of the classic ruleset
(assets/rules/classic/*.ron) as messages `classic.<kind>.<id>.name|desc` (docs/localization.md,
section 6). Rule data keeps its text; this file is the English bundle's copy of it, and the
base of the other languages' content files. Run after the ruleset is regenerated."""
import glob, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
KIND = {
    'units': 'unit', 'buildings': 'building', 'technologies': 'tech', 'policy_branches': 'policy', 'policies': 'policy',
    'promotions': 'promotion', 'beliefs': 'belief', 'nations': 'nation', 'great_people': 'great-person', 'eras': 'era',
    'terrains': 'terrain', 'features': 'feature', 'resources': 'resource', 'improvements': 'improvement',
    'natural_wonders': 'natural-wonder', 'city_states': 'city-state', 'projects': 'project', 'specialists': 'specialist',
    'handicaps': 'handicap', 'religions': 'religion', 'city_state_types': 'city-state-type',
}
FIELD = {'name': 'name', 'text': 'desc'}


def slug(i):
    # the same rule as i18n::content_slug
    i = i[5:] if i.startswith('core:') else i
    if '/' in i:
        i = i.split('/', 1)[1] or i
    if '/' not in i and '_' in i and not any(c.islower() for c in i):
        i = i.split('_', 1)[1]
    return i.lower().replace('/', '.').replace('_', '-').replace(':', '-').replace(' ', '-')


def unquote(s):
    return s.replace('\\"', '"').replace('\\\\', '\\')


# Typos of the ruleset's prose, corrected in the bundle only (the data is hashed: it keeps them).
TYPOS = {'Ampitheater': 'Amphitheater', 'abilties': 'abilities', 'Targetting': 'Targeting'}


def nation_words(text):
    """The project's word for the concept is "nation" (the project owner, 2026-10-20): the ruleset's
    prose says "nation(s)"; the bundle says "nation(s)"."""
    def swap(m):
        word = m.group(0)
        out = 'nation' + ('s' if word.lower().endswith('s') else '')
        return out.capitalize() if word[0].isupper() else out
    text = re.sub(r'\bnations?\b', swap, text, flags=re.I)
    for wrong, right in TYPOS.items():
        text = text.replace(wrong, right)
    return text


def main():
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'assets/rules/classic/*.ron'))):
        lst = None
        item = None
        for line in open(path, encoding='utf-8'):
            m = re.match(r'^    (\w+): \[', line)
            if m:
                lst = m.group(1)
                continue
            if re.match(r'^        \($', line) or re.match(r'^        \(id:', line):
                item = {'list': lst}
                if 'id:' in line:
                    mm = re.search(r'id: "([^"]*)"', line)
                    item['id'] = mm.group(1)
                continue
            m = re.match(r'^            (id|name|text): "((?:[^"\\]|\\.)*)",?$', line)
            if m and item is not None and lst in KIND:
                item[m.group(1)] = unquote(m.group(2))
            if re.match(r'^        \),?$', line) and item is not None:
                if item.get('list') in KIND and 'id' in item:
                    kind = KIND[item['list']]
                    for f, k in FIELD.items():
                        if f in item and item[f].strip():
                            key = f"classic.{kind}.{slug(item['id'])}.{k}"
                            if key in out and out[key] != item[f]:
                                print('duplicate key with another text:', key, file=sys.stderr)
                            out.setdefault(key, nation_words(item[f]))
                item = None
    lines = ['# The English names of the classic ruleset (generated by tools/i18n/gen_content_classic.py).',
             '# Keys: classic.<kind>.<id>.name. Descriptions are made from the typed effects (no prose is kept); do not edit by hand.', '']
    last = None
    for key in sorted(out, key=lambda k: (k.split('.')[1], k)):
        kind = key.split('.')[1]
        if kind != last:
            lines += ['', f'## {kind}']
            last = kind
        text = out[key].replace('\n', '\n    ')
        lines.append(f'{key} = {text}')
    path = os.path.join(ROOT, 'assets/lang/en/content-classic.ftl')
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(len(out), 'messages ->', path)


main()
